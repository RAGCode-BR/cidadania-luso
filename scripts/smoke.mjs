import assert from "node:assert/strict";
import { chromium } from "playwright";

const browser = await chromium.launch({ executablePath: process.env.BROWSER_PATH || "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 950 }, locale: "pt-BR" });
const page = await context.newPage();
const errors = [];
page.on("pageerror", (error) => errors.push(error.message));
try {
  await page.goto(process.env.TEST_APP_URL || "http://127.0.0.1:5180/");
  await page.getByRole("heading", { name: "Oportunidades em movimento." }).waitFor();
  await page.getByRole("button", { name: "Nova oportunidade" }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByLabel("Cliente / obra").fill("Obra Alfa");
  await dialog.getByLabel("Rua / avenida").fill("Rua Alfa");
  await dialog.getByLabel("Número").fill("10");
  await dialog.getByLabel("Bairro").fill("Centro");
  await dialog.getByLabel("Cidade").fill("São Paulo");
  await dialog.getByLabel("UF").fill("SP");
  await dialog.getByLabel("Produtos a negociar").fill("Forro, Divisória");
  await dialog.getByRole("button", { name: "Adicionar cartão" }).click();
  await page.locator(".crm-card-title", { hasText: "Obra Alfa" }).waitFor();
  await page.locator(".crm-card-title", { hasText: "Obra Alfa" }).click();
  await dialog.getByRole("button", { name: "Registrar venda" }).click();
  await dialog.getByRole("checkbox", { name: "FORRO" }).check();
  await dialog.getByLabel("Valor deste fechamento (R$)").fill("500");
  await dialog.getByRole("button", { name: "Confirmar venda" }).click();
  await dialog.waitFor({ state: "hidden" });
  await page.locator(".crm-card-title", { hasText: "Obra Alfa" }).click();
  await dialog.getByRole("button", { name: "Registrar visita" }).click();
  await dialog.getByLabel("Anotações").fill("Cliente pediu retorno na próxima semana.");
  await dialog.getByRole("button", { name: "Salvar visita" }).click();
  await dialog.waitFor({ state: "hidden" });
  await page.getByRole("button", { name: "Serviços", exact: true }).click();
  await page.getByRole("button", { name: "Vendas para instalação" }).click();
  await page.getByText("Obra Alfa", { exact: true }).waitFor();
  await page.getByRole("button", { name: "Gerar serviço" }).click();
  await dialog.getByLabel("Serviço a executar").fill("Instalar forro");
  await dialog.getByRole("button", { name: "Salvar serviço" }).click();
  await dialog.getByText("Aguardando agendamento").waitFor();
  await page.getByRole("button", { name: "Fechar janela" }).click();
  await page.getByRole("button", { name: "Equipe de execução" }).click();
  await page.getByLabel("Nome do profissional").fill("Ana");
  await page.getByRole("button", { name: "Cadastrar profissional" }).click();
  await page.getByRole("button", { name: "Todos os serviços" }).click();
  await page.getByRole("button", { name: "Obra Alfa", exact: true }).click();
  await dialog.getByRole("button", { name: "Editar / agendar" }).click();
  await dialog.getByRole("button", { name: "Adicionar agendamento" }).click();
  const appointment = dialog.locator(".service-appointment-form");
  const date = new Date().toLocaleDateString("pt-BR", { timeZone: "America/Sao_Paulo" });
  await appointment.getByRole("textbox", { name: /^Data inicial/ }).fill(date);
  await appointment.getByRole("textbox", { name: /^Data final/ }).fill(date);
  await appointment.getByLabel("Ana", { exact: true }).check();
  await dialog.getByRole("button", { name: "Salvar serviço" }).click();
  await dialog.getByText("Agendado", { exact: true }).waitFor();
  await page.getByRole("button", { name: "Fechar janela" }).click();
  await page.reload();
  await page.getByRole("button", { name: "Serviços", exact: true }).click();
  await page.getByRole("button", { name: "Todos os serviços" }).click();
  await page.getByText("SV-0001").first().waitFor();
  assert.deepEqual(errors, []);
  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, locale: "pt-BR" });
  const phone = await mobile.newPage();
  await phone.goto(process.env.TEST_APP_URL || "http://127.0.0.1:5180/");
  await phone.getByRole("button", { name: "Abrir navegação" }).click();
  await phone.getByRole("navigation", { name: "Navegação principal" }).getByRole("button", { name: "Serviços" }).click();
  await phone.getByRole("heading", { name: "Da venda à entrega." }).waitFor();
  assert.equal(await phone.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await mobile.close();
  console.log("PASS: oportunidade, venda, visita, agendamento e persistência após recarga");
} catch (error) {
  await page.screenshot({ path: "test-results/luso-failure.png", fullPage: true }).catch(() => {});
  console.error("Erros da página:", errors);
  throw error;
} finally { await context.close(); await browser.close(); }
