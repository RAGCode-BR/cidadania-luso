import assert from "node:assert/strict";
import { chromium } from "playwright";

const browser = await chromium.launch({ executablePath: process.env.BROWSER_PATH || "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 950 }, locale: "pt-BR" });
const page = await context.newPage();
const errors = [];
page.on("pageerror", (error) => errors.push(error.message));
try {
  await page.goto(process.env.TEST_APP_URL || "http://127.0.0.1:5180/");
  await page.getByRole("heading", { name: "CRM", level: 1 }).waitFor();
  await page.getByRole("button", { name: "Nova oportunidade" }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByLabel("Nome do cliente").fill("Maria Alfa");
  await dialog.getByLabel("Telefone").fill("(11) 91234-5678");
  await dialog.getByLabel("E-mail").fill("maria@exemplo.com");
  await dialog.getByLabel("Produtos a negociar").fill("Forro, Divisória");
  await dialog.getByRole("button", { name: "Adicionar cartão" }).click();
  await page.locator(".crm-card-title", { hasText: "Maria Alfa" }).waitFor();
  await page.locator(".crm-card-title", { hasText: "Maria Alfa" }).click();
  await dialog.getByRole("button", { name: "Registrar venda" }).click();
  await dialog.getByRole("checkbox", { name: "FORRO" }).check();
  await dialog.getByLabel("Valor deste fechamento (R$)").fill("500");
  await dialog.getByRole("button", { name: "Confirmar venda" }).click();
  await dialog.waitFor({ state: "hidden" });
  await page.locator(".crm-card-title", { hasText: "Maria Alfa" }).click();
  await dialog.getByRole("button", { name: "Registrar atendimento" }).click();
  await dialog.getByLabel("Anotações").fill("Cliente pediu retorno na próxima semana.");
  await dialog.getByLabel("Forma de contato").selectOption("call");
  await dialog.getByRole("button", { name: "Salvar atendimento" }).click();
  await dialog.waitFor({ state: "hidden" });
  await page.locator(".crm-card", { hasText: "Maria Alfa" }).getByText("1 atendimento").waitFor();
  await page.locator(".crm-card-title", { hasText: "Maria Alfa" }).click();
  const history = dialog.getByRole("region", { name: "Atendimentos do cliente" });
  await history.getByText(/Ligação/).waitFor();
  await history.getByText("Cliente pediu retorno na próxima semana.").waitFor();
  await dialog.getByRole("link", { name: "maria@exemplo.com" }).waitFor();
  await page.getByRole("button", { name: "Fechar janela" }).click();
  const nav = page.getByRole("navigation", { name: "Navegação principal" });
  await nav.getByRole("button", { name: "Produtos" }).click();
  await page.getByRole("heading", { name: "Produtos", level: 1 }).waitFor();
  const list = page.getByRole("list", { name: "Produtos cadastrados" });
  await list.getByText("FORRO", { exact: true }).waitFor();
  await list.getByText("DIVISÓRIA", { exact: true }).waitFor();
  await page.getByRole("button", { name: "Novo produto" }).click();
  await dialog.getByLabel("Nome do produto").fill("Piso vinílico");
  await dialog.getByLabel("Descrição").fill("Régua 18 x 122 cm");
  await dialog.getByLabel("Preço de referência (R$)").fill("120.5");
  await dialog.getByRole("button", { name: "Cadastrar produto" }).click();
  await dialog.waitFor({ state: "hidden" });
  await list.getByText("R$ 120,50").waitFor();
  await page.getByRole("button", { name: "Editar FORRO" }).click();
  await dialog.getByLabel("Nome do produto").fill("Forro mineral");
  await dialog.getByText("passarão a mostrar o novo nome").waitFor();
  await dialog.getByRole("button", { name: "Salvar alterações" }).click();
  await dialog.waitFor({ state: "hidden" });
  await list.getByText("FORRO MINERAL", { exact: true }).waitFor();
  await page.getByRole("button", { name: "Excluir DIVISÓRIA" }).click();
  await dialog.getByRole("button", { name: "Excluir produto" }).click();
  await dialog.waitFor({ state: "hidden" });
  assert.equal(await list.getByText("DIVISÓRIA", { exact: true }).count(), 0);
  await page.reload();
  await page.getByRole("navigation", { name: "Navegação principal" }).getByRole("button", { name: "Produtos" }).click();
  await list.getByText("FORRO MINERAL", { exact: true }).waitFor();
  await list.getByText("PISO VINÍLICO", { exact: true }).waitFor();
  await page.getByRole("navigation", { name: "Navegação principal" }).getByRole("button", { name: "CRM" }).click();
  // Produto excluído continua no cartão que já o citava.
  await page.locator(".crm-card", { hasText: "Maria Alfa" }).getByText("DIVISÓRIA", { exact: true }).waitFor();
  // A busca do CRM considera só o nome do cliente.
  await page.getByLabel("Buscar cliente").fill("maria alfa");
  await page.locator(".crm-card", { hasText: "Maria Alfa" }).waitFor();
  await page.getByLabel("Buscar cliente").fill("forro mineral");
  await page.locator(".crm-card", { hasText: "Maria Alfa" }).waitFor({ state: "detached" });
  await page.getByLabel("Buscar cliente").fill("");
  // Filtro por produto: PISO VINÍLICO não está no cartão de Maria Alfa.
  await page.getByLabel("Produto", { exact: true }).selectOption("PISO VINÍLICO");
  await page.locator(".crm-card", { hasText: "Maria Alfa" }).waitFor({ state: "detached" });
  await page.getByLabel("Produto", { exact: true }).selectOption("DIVISÓRIA");
  await page.locator(".crm-card", { hasText: "Maria Alfa" }).waitFor();
  await page.getByLabel("Produto", { exact: true }).selectOption("");
  await page.getByRole("button", { name: "Nova oportunidade" }).click();
  await dialog.getByLabel("Nome do cliente").fill("João Beta");
  assert.equal(await dialog.getByRole("checkbox", { name: "DIVISÓRIA" }).count(), 0);
  await dialog.getByRole("checkbox", { name: "PISO VINÍLICO" }).check();
  await dialog.getByRole("button", { name: "Adicionar cartão" }).click();
  await dialog.waitFor({ state: "hidden" });
  await page.locator(".crm-card", { hasText: "João Beta" }).getByText(/PISO VINÍLICO/).first().waitFor();
  // Excluir exige motivo; o cartão vai para a aba Excluídos com quem, quando e por quê.
  await page.getByRole("button", { name: "Excluir cartão João Beta" }).click();
  const confirm = dialog.getByRole("button", { name: "Excluir cartão" });
  assert.equal(await confirm.isDisabled(), true);
  await dialog.getByLabel("Motivo da exclusão").fill("Cadastro duplicado do mesmo cliente.");
  await confirm.click();
  await dialog.waitFor({ state: "hidden" });
  assert.equal(await page.locator(".crm-card", { hasText: "João Beta" }).count(), 0);
  await page.getByRole("button", { name: /Excluídos/ }).click();
  const deleted = page.locator(".crm-deleted-row", { hasText: "João Beta" });
  await deleted.getByText("Cadastro duplicado do mesmo cliente.").waitFor();
  await deleted.getByText("Equipe Luso").first().waitFor();
  await deleted.getByRole("button", { name: "Ver histórico de João Beta" }).click();
  await dialog.getByRole("note").getByText(/Motivo: Cadastro duplicado/).waitFor();
  assert.equal(await dialog.getByRole("button", { name: "Registrar atendimento" }).count(), 0);
  await page.getByRole("button", { name: "Fechar janela" }).click();
  await page.getByRole("button", { name: /Em andamento/ }).click();
  assert.deepEqual(errors, []);
  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, locale: "pt-BR" });
  const phone = await mobile.newPage();
  await phone.goto(process.env.TEST_APP_URL || "http://127.0.0.1:5180/");
  await phone.getByRole("heading", { name: "CRM", level: 1 }).waitFor();
  await phone.getByRole("navigation", { name: "Navegação principal" }).getByRole("button", { name: "Produtos" }).click();
  await phone.getByRole("heading", { name: "Produtos", level: 1 }).waitFor();
  assert.equal(await phone.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await mobile.close();
  console.log("PASS: oportunidade, venda, atendimento, cadastro/edição/exclusão de produtos, exclusão de cartão com motivo e persistência após recarga");
} catch (error) {
  await page.screenshot({ path: "test-results/luso-failure.png", fullPage: true }).catch(() => {});
  console.error("Erros da página:", errors);
  throw error;
} finally { await context.close(); await browser.close(); }
